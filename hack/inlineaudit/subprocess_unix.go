package main

import (
	"errors"
	"os/exec"
	"syscall"
)

// stopWithItsChildren gives a command a process group of its own and makes stopping it
// kill the whole group, so the compiler the go command started stops with it.
//
// Takes command (*exec.Cmd) which is the command, not yet started.
func stopWithItsChildren(command *exec.Cmd) {
	command.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	command.Cancel = func() error {
		if command.Process == nil {
			return nil
		}
		err := syscall.Kill(-command.Process.Pid, syscall.SIGKILL)
		if errors.Is(err, syscall.ESRCH) {
			return nil
		}
		return err
	}
	command.WaitDelay = stoppedBuildWaitDelay
}
