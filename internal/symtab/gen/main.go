// This project stands against fascism, authoritarianism, and all forms of
// oppression. We built this to empower people, not to enable those who would
// strip others of their rights and dignity.

// Code generated by go run ./internal/symtab/gen. DO NOT EDIT.`

func main() {
	count := flag.Int("count", defaultColumnCount, "number of pool columns to declare")
	output := flag.String("out", defaultOutputPath, "path of the generated file")
	validate := flag.Bool("validate", false, "fail when the committed file differs from what would be generated")
	flag.Parse()

	source, err := render(*count)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(2)
	}

	if *validate {
		existing, readErr := os.ReadFile(*output)
		if readErr != nil {
			fmt.Fprintf(os.Stderr, "gen: reading %s: %v\n", *output, readErr)
			os.Exit(2)
		}
		if !bytes.Equal(existing, source) {
			fmt.Fprintf(os.Stderr, "gen: %s is stale; run make generate-named-scalar-tags\n", *output)
			os.Exit(1)
		}
		fmt.Printf("gen: %s is up to date\n", *output)
		return
	}

	if writeErr := os.WriteFile(*output, source, outputFilePerm); writeErr != nil {
		fmt.Fprintf(os.Stderr, "gen: writing %s: %v\n", *output, writeErr)
		os.Exit(2)
	}
	fmt.Printf("gen: wrote %s (%d columns)\n", *output, *count)
}

// render produces the gofmt-formatted source for count columns.
//
// Takes count (int) which is the number of pool columns to declare.
//
// Returns []byte which is the formatted source.
// Returns error when rendering fails.
func render(count int) ([]byte, error) {
	tags := &ast.GenDecl{Tok: token.TYPE, Lparen: 1}
	columns := gosource.Lines(&ast.CompositeLit{
		Type: &ast.ArrayType{
			Len: ast.NewIdent("namedScalarPoolGeneratedColumns"),
			Elt: &ast.ArrayType{
				Len: ast.NewIdent("namedScalarKindRows"),
				Elt: &ast.SelectorExpr{X: ast.NewIdent("reflect"), Sel: ast.NewIdent("Type")},
			},
		},
	})
	for index := range count {
		tag := fmt.Sprintf("namedScalarTag%03d", index)
		tags.Specs = append(tags.Specs, &ast.TypeSpec{
			Name: ast.NewIdent(tag),
			Type: &ast.StructType{Fields: &ast.FieldList{}},
		})
		columns.Elts = append(columns.Elts, &ast.CallExpr{
			Fun: &ast.IndexExpr{X: ast.NewIdent("namedScalarPoolColumn"), Index: ast.NewIdent(tag)},
		})
	}
	file := gosource.File{
		Header:                    fileHeader,
		BuildConstraint:           "",
		Package:                   "typemodel",
		ImportGroups:              [][]gosource.Import{{{Path: "reflect", Name: ""}}},
		LoneImportUnparenthesised: false,
		Declarations: []gosource.Declaration{
			{Doc: nil, Directives: nil, Node: &ast.GenDecl{
				Tok: token.CONST,
				Specs: []ast.Spec{&ast.ValueSpec{
					Names:  []*ast.Ident{ast.NewIdent("namedScalarPoolGeneratedColumns")},
					Values: []ast.Expr{&ast.BasicLit{Kind: token.INT, Value: strconv.Itoa(count)}},
				}},
			}},
			{Doc: nil, Directives: nil, Node: tags},
			{Doc: nil, Directives: nil, Node: &ast.GenDecl{
				Tok:    token.VAR,
				Lparen: 1,
				Specs: []ast.Spec{&ast.ValueSpec{
					Names:  []*ast.Ident{ast.NewIdent("namedScalarPoolColumns")},
					Values: []ast.Expr{columns},
				}},
			}},
		},
	}
	source, err := file.Render()
	if err != nil {
		return nil, fmt.Errorf("rendering generated source: %w", err)
	}
	return source, nil
}
