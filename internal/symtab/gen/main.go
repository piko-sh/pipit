// Command gen emits the file named_scalar_pool_tags_gen.go: one zero-size tag struct per
// pool column plus the namedScalarPoolColumns table that instantiates the per-kind
// generic pool types over every tag. The column count bounds how many distinct
// user-declared named basic types per kind keep a distinct reflect identity before the
// pool exhausts and falls back to collapsing.
//
// Usage:
//
//	go run ./internal/symtab/gen [-count 512]
//	go run ./internal/symtab/gen -validate
//
// 256 columns cost a further 1.3 MB of binary for the extra generic instantiations.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
)

const (
	defaultColumnCount = 512

	defaultOutputPath = "internal/symtab/typemodel/named_scalar_pool_tags_gen.go"

	outputFilePerm = 0o644
)

const fileHeader = `// Copyright 2026 PolitePixels Limited
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// This project stands against fascism, authoritarianism, and all forms of
// oppression. We built this to empower people, not to enable those who would
// strip others of their rights and dignity.

// Code generated by go run ./internal/symtab/gen. DO NOT EDIT.

package typemodel

import (
	"reflect"
)

`

func main() {
	count := flag.Int("count", defaultColumnCount, "number of pool columns to declare")
	output := flag.String("out", defaultOutputPath, "path of the generated file")
	validate := flag.Bool("validate", false, "fail when the committed file differs from what would be generated")
	flag.Parse()

	source, err := render(*count)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(2)
	}

	if *validate {
		existing, readErr := os.ReadFile(*output)
		if readErr != nil {
			fmt.Fprintf(os.Stderr, "gen: reading %s: %v\n", *output, readErr)
			os.Exit(2)
		}
		if !bytes.Equal(existing, source) {
			fmt.Fprintf(os.Stderr, "gen: %s is stale; run make generate-named-scalar-tags\n", *output)
			os.Exit(1)
		}
		fmt.Printf("gen: %s is up to date\n", *output)
		return
	}

	if writeErr := os.WriteFile(*output, source, outputFilePerm); writeErr != nil {
		fmt.Fprintf(os.Stderr, "gen: writing %s: %v\n", *output, writeErr)
		os.Exit(2)
	}
	fmt.Printf("gen: wrote %s (%d columns)\n", *output, *count)
}

// render produces the gofmt-formatted source for count columns.
//
// Takes count (int) which is the number of pool columns to declare.
//
// Returns the formatted source bytes and any error.
func render(count int) ([]byte, error) {
	var buffer bytes.Buffer
	buffer.WriteString(fileHeader)

	fmt.Fprintf(&buffer, "const namedScalarPoolGeneratedColumns = %d\n\n", count)

	buffer.WriteString("type (\n")
	for index := range count {
		fmt.Fprintf(&buffer, "\tnamedScalarTag%03d struct{}\n", index)
	}
	buffer.WriteString(")\n\n")

	buffer.WriteString("var (\n")
	buffer.WriteString("\tnamedScalarPoolColumns = [namedScalarPoolGeneratedColumns][namedScalarKindRows]reflect.Type{\n")
	for index := range count {
		fmt.Fprintf(&buffer, "\t\tnamedScalarPoolColumn[namedScalarTag%03d](),\n", index)
	}
	buffer.WriteString("\t}\n)\n")

	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return formatted, nil
}
