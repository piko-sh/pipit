package isa

import (
	"fmt"
	"strings"
)

// tierCount is the number of encoding tiers.
const tierCount = 4

// Tier is the encoding depth an operation lives at: the byte position whose value selects
// it once every shallower position holds the "descend" marker.
type Tier uint8

const (
	// TierMain is the op byte itself: three-operand instructions.
	TierMain Tier = iota

	// TierSub1 is operand A when the op byte is OpDrillTier1: two-operand instructions.
	TierSub1

	// TierSub2 is operand B when A is also SubOpDrillTier2: one-operand instructions.
	TierSub2

	// TierSub3 is operand C when B is also SubOpTier2DrillTier3: zero-operand instructions.
	TierSub3
)

// specFlag carries the yes/no properties of an operation.
type specFlag uint16

const (
	// SpecJump marks an operation that carries a relative jump offset. JumpLayoutOf returns
	// where the offset is encoded.
	SpecJump specFlag = 1 << iota

	// specReserved marks a retired slot kept so the numbering of later operations does not
	// shift. It has no handler and no name.
	specReserved

	// specMeta marks a drill marker: index 0 of a tier, which means "descend a tier" rather
	// than an operation in its own right.
	specMeta

	// SpecShimNarrow selects the slim assembly shim for an operation lifted through a tier-2
	// shim: the handler neither reads nor writes the program counter, so the shim skips the
	// PC save and restore around the Go call.
	SpecShimNarrow

	// SpecShimSuppressed keeps the shim emitted as a fallback jump target while a pure
	// assembly body owns the operation's jump-table slot.
	SpecShimSuppressed

	// specMutatesMemory marks an operation that can mutate state reachable from outside its
	// own register writes. The optimiser's heap-effect predicate derives from this flag.
	specMutatesMemory

	// specMemoryPure marks an operation that provably mutates no reachable state. Stated
	// explicitly so a new operation carrying neither flag is a classification gap the ISA
	// spec test rejects.
	specMemoryPure

	// specCalls marks an operation that transfers control to a callee.
	specCalls

	// specPublishes marks an operation that makes a value visible beyond the VM's own
	// registers (a return, a panic, a send), so its row must declare its hand-offs.
	specPublishes
)

// symbolSet records which derived symbols an operation has besides its Go handler.
type symbolSet uint8

const (
	// symbolAsm marks an operation with an assembly body.
	symbolAsm symbolSet = 1 << iota

	// symbolShim marks an operation that reaches its Go handler through a tier-2 shim.
	symbolShim

	// symbolExit marks an operation routed to Go through a dedicated exit stub.
	symbolExit

	// symbolNoGoHandler marks a row the dispatch loop never runs as an operation of its own
	// (a drill marker, or a table row another operation reads), so it has no Go handler.
	symbolNoGoHandler
)

// DispatchPath is how the assembly dispatch loop runs an operation.
type DispatchPath uint8

const (
	// DispatchNone marks a row the loop never dispatches on its own: drill markers and
	// reserved slots.
	DispatchNone DispatchPath = iota

	// DispatchAsm runs in an assembly body. A slow path may still call into Go or exit.
	DispatchAsm

	// DispatchShim calls its Go handler through an in-loop shim on every execution, without
	// leaving the loop.
	DispatchShim

	// DispatchExit leaves the loop for Go through a dedicated exit stub.
	DispatchExit

	// DispatchGo leaves the loop for Go through the generic path-B exit.
	DispatchGo
)

// OpSpec is the single record everything else about an operation derives from.
//
// The enum constant is the operation's one hand-written name. The printed name derives
// from it (specNames, generated by gen_spec_names.go), and every symbol derives from the
// printed name's CamelCase stem. For SubOpLoadInt64Immediate the name is
// LOAD_INT64_IMMEDIATE, the Go handler handleLoadInt64Immediate, the assembly body
// handlerLoadInt64Immediate, the shim suffix LoadInt64Immediate with trampoline
// HandleLoadInt64Immediate, and the exit stub handlerLoadInt64ImmediateExit with reason
// exitLoadInt64Immediate.
type OpSpec struct {
	// Name is the mnemonic the disassembler prints, for example "ADD_INT64".
	Name string

	// Handler is the Go handler the flat dispatch switch calls, "handle" and the stem, for
	// example "handleAddInt64". Empty for drill markers, reserved slots and table rows.
	Handler string

	// AsmBody is the assembly handler symbol that owns the jump-table slot, "handler" and
	// the stem, for example "handlerAddInt64". Empty when the operation has no assembly
	// body.
	AsmBody string

	// AsmTable names the jump table the body is installed in; empty means the main table.
	AsmTable string

	// Shim is the suffix of the tier-2 assembly-call shim, the stem, for example
	// "TypeAssert", when the operation reaches its Go handler through a shim. Empty
	// otherwise.
	Shim string

	// ShimHandler is the exported Go trampoline target the shim calls, "Handle" and the
	// stem, for example "HandleTypeAssert".
	ShimHandler string

	// ExitStub is the assembly exit stub that routes the operation to Go through a dedicated
	// exit reason, for example "handlerSetFieldExit". Empty otherwise.
	ExitStub string

	// ExitReason names the exit constant the stub writes, for example "exitSetField".
	ExitReason string

	// HandOff records how the operation handles a value that may leave the arena's lifetime.
	HandOff []HandOffEntry

	// Cost is the cost-table charge for one execution of the operation.
	Cost int64

	// Flags are the operation's yes/no properties.
	Flags specFlag

	// Tier is the encoding depth.
	Tier Tier

	// Code is the operation's value within its tier: the enum constant.
	Code uint8

	// symbols records which derived symbols the operation has.
	symbols symbolSet
}

// symbolInitialisms are the printed-name words a derived symbol keeps in upper case.
var symbolInitialisms = map[string]bool{"IIFE": true}

// specIndex holds every row by tier and code for O(1) lookup, built once from the tier
// slices.
var specIndex [tierCount][256]*OpSpec

// Has reports whether the row carries every flag in f.
//
// Takes f (specFlag) which is the flag mask to test.
//
// Returns true when all bits in f are set.
func (s OpSpec) Has(f specFlag) bool { return s.Flags&f == f }

// Shape returns the operand Shape recorded for the operation.
//
// Every tier carries its own shapes, so a tier-1 row describes its own operands rather
// than borrowing the OpDrillTier1 wildcard.
//
// Returns OperandShape which is the recorded Shape, or the zero Shape when none is
// described.
func (s OpSpec) Shape() OperandShape {
	return OperandShapeAt(s.Tier, s.Code)
}

// MutatesMemory reports whether the operation can mutate memory beyond its register
// writes, and whether the operation was classified at all.
//
// Returns mutates (bool) which is true when specMutatesMemory is set.
// Returns classified (bool) which is false when the row carries neither memory flag, in
// which case callers must treat the operation as mutating.
func (s OpSpec) MutatesMemory() (mutates, classified bool) {
	if s.Has(specMutatesMemory) {
		return true, true
	}
	if s.Has(specMemoryPure) {
		return false, true
	}
	return true, false
}

// Dispatch reports how the assembly dispatch loop runs the operation.
//
// Returns DispatchPath which classifies the operation's jump-table slot.
func (s OpSpec) Dispatch() DispatchPath {
	switch {
	case s.Handler == "":
		return DispatchNone
	case s.ExitStub != "":
		return DispatchExit
	case s.AsmBody != "":
		return DispatchAsm
	case s.Shim != "":
		return DispatchShim
	default:
		return DispatchGo
	}
}

// ExitsLoop reports whether dispatch leaves the assembly loop for Go, the round trip the
// path-B batch amortises.
//
// Returns bool which is true for DispatchExit and DispatchGo.
func (p DispatchPath) ExitsLoop() bool {
	return p == DispatchExit || p == DispatchGo
}

// String renders the row for diagnostics.
//
// Returns a formatted string showing tier, code and name.
func (s OpSpec) String() string {
	return fmt.Sprintf("tier%d:%d %s", s.Tier, s.Code, s.Name)
}

// cost sets the cost-table charge.
//
// Takes charge (int64) which is the per-execution cost weight.
//
// Returns OpSpec with the updated cost.
func (s OpSpec) cost(charge int64) OpSpec { s.Cost = charge; return s }

// noGoHandler marks a row the dispatch loop never runs as an operation of its own (a
// drill marker, or a table row another operation reads), so it has no Go handler.
//
// Returns OpSpec without a Go handler.
func (s OpSpec) noGoHandler() OpSpec { s.symbols |= symbolNoGoHandler; return s }

// asm gives the operation an assembly body that owns its main jump-table slot.
//
// Returns OpSpec with an assembly body.
func (s OpSpec) asm() OpSpec { s.symbols |= symbolAsm; return s }

// asmIn gives the operation an assembly body installed in the named jump table.
//
// Takes table (string) which is the jump table name.
//
// Returns OpSpec with an assembly body and its table.
func (s OpSpec) asmIn(table string) OpSpec { s.symbols |= symbolAsm; s.AsmTable = table; return s }

// shim binds the operation to a tier-2 assembly-call shim and its exported trampoline.
//
// Returns OpSpec with a shim.
func (s OpSpec) shim() OpSpec { s.symbols |= symbolShim; return s }

// exit binds the operation to a direct exit stub and its exit reason.
//
// Returns OpSpec with an exit stub.
func (s OpSpec) exit() OpSpec { s.symbols |= symbolExit; return s }

// flags ORs properties onto the row.
//
// Takes f (specFlag) which is the flag bits to add.
//
// Returns OpSpec with the additional flags.
func (s OpSpec) flags(f specFlag) OpSpec { s.Flags |= f; return s }

// mutates marks the operation as able to mutate memory beyond its own register writes.
//
// Returns OpSpec with specMutatesMemory set.
func (s OpSpec) mutates() OpSpec { s.Flags |= specMutatesMemory; return s }

// pure marks the operation as mutating no memory beyond its own register writes.
//
// Returns OpSpec with specMemoryPure set.
func (s OpSpec) pure() OpSpec { s.Flags |= specMemoryPure; return s }

// AllSpecs returns every row in tier order then code order.
//
// Returns []OpSpec containing all registered spec rows.
func AllSpecs() []OpSpec {
	all := make([]OpSpec, 0, len(tierMainSpecs)+len(tierSub1Specs)+len(tierSub2Specs)+len(tierSub3Specs))
	for tier := range specIndex {
		for code := range specIndex[tier] {
			if row := specIndex[tier][code]; row != nil {
				all = append(all, *row)
			}
		}
	}
	return all
}

// SpecAt returns the row for a tier and code, and whether one exists.
//
// Takes tier (Tier) which is the encoding depth.
// Takes code (uint8) which is the operation value within its tier.
//
// Returns OpSpec and true when a row exists, or the zero spec and false otherwise.
func SpecAt(tier Tier, code uint8) (OpSpec, bool) {
	if int(tier) >= tierCount {
		return OpSpec{}, false
	}
	row := specIndex[tier][code]
	if row == nil {
		return OpSpec{}, false
	}
	return *row, true
}

// SpecFor returns the row for a tier-0 opcode.
//
// Takes op (Opcode) which is the tier-0 opcode to look up.
//
// Returns OpSpec and true when a row exists, or the zero spec and false otherwise.
func SpecFor(op Opcode) (OpSpec, bool) { return SpecAt(TierMain, uint8(op)) }

// SpecForInstruction resolves the drill cascade and returns the row the instruction
// executes.
//
// Takes instruction (Instruction) which is the encoded instruction word.
//
// Returns OpSpec which is the instruction row, or the zero spec.
// Returns bool which is true when a row exists.
func SpecForInstruction(instruction Instruction) (OpSpec, bool) {
	if instruction.Op != OpDrillTier1 {
		return SpecAt(TierMain, uint8(instruction.Op))
	}
	if SubOpcode(instruction.A) != SubOpDrillTier2 {
		return SpecAt(TierSub1, instruction.A)
	}
	if SubOpcodeTier2(instruction.B) != SubOpTier2DrillTier3 {
		return SpecAt(TierSub2, instruction.B)
	}
	return SpecAt(TierSub3, instruction.C)
}

// DispatchForInstruction reports how the assembly dispatch loop runs an instruction word.
//
// It differs from the row's Dispatch for the all-zero no-op. It has no assembly body of
// its own, but the loop's dispatch sequence skips it without leaving assembly, so it
// never takes the generic exit its row would suggest.
//
// Takes instruction (Instruction) which is the encoded instruction word.
//
// Returns DispatchPath which is DispatchNone for a word with no row.
func DispatchForInstruction(instruction Instruction) DispatchPath {
	if instruction == (Instruction{}) {
		return DispatchAsm
	}
	spec, ok := SpecForInstruction(instruction)
	if !ok {
		return DispatchNone
	}
	return spec.Dispatch()
}

// specRowForInstruction resolves the drill cascade to the row the instruction executes,
// without copying it.
//
// Takes instruction (Instruction) which is the encoded instruction word.
//
// Returns *OpSpec which is the row, or nil when none exists. The row is shared and must
// not be changed.
func specRowForInstruction(instruction Instruction) *OpSpec {
	if instruction.Op != OpDrillTier1 {
		return specIndex[TierMain][instruction.Op]
	}
	if SubOpcode(instruction.A) != SubOpDrillTier2 {
		return specIndex[TierSub1][instruction.A]
	}
	if SubOpcodeTier2(instruction.B) != SubOpTier2DrillTier3 {
		return specIndex[TierSub2][instruction.B]
	}
	return specIndex[TierSub3][instruction.C]
}

// InstructionMutatesMemory reports whether the operation an instruction executes can
// mutate memory beyond its register writes, and whether the operation was classified at
// all.
//
// Takes instruction (Instruction) which is the encoded instruction word.
//
// Returns mutates (bool) which is true when the operation can mutate such memory, and
// when it has no row or no memory classification.
// Returns classified (bool) which is false when the operation has no row or carries
// neither memory flag, in which case callers must treat it as mutating.
func InstructionMutatesMemory(instruction Instruction) (mutates, classified bool) {
	row := specRowForInstruction(instruction)
	switch {
	case row == nil:
		return true, false
	case row.Flags&specMutatesMemory != 0:
		return true, true
	case row.Flags&specMemoryPure != 0:
		return false, true
	default:
		return true, false
	}
}

// spec starts a row for an operation at a tier. Its name and symbols are filled in by
// deriveSymbols once every row is registered.
//
// Takes tier (Tier) which is the encoding depth.
// Takes code (uint8) which is the operation value within its tier.
//
// Returns OpSpec with the baseline fields populated.
func spec(tier Tier, code uint8) OpSpec {
	return OpSpec{
		Name:        "",
		Handler:     "",
		AsmBody:     "",
		AsmTable:    "",
		Shim:        "",
		ShimHandler: "",
		ExitStub:    "",
		ExitReason:  "",
		Cost:        costCheap,
		HandOff:     nil,
		Flags:       0,
		Tier:        tier,
		Code:        code,
		symbols:     0,
	}
}

// main0 starts a tier-0 row.
//
// Takes op (Opcode) which is the tier-0 opcode.
//
// Returns OpSpec with tier set to TierMain.
func main0(op Opcode) OpSpec { return spec(TierMain, uint8(op)) }

// sub1 starts a tier-1 row.
//
// Takes op (SubOpcode) which is the tier-1 sub-opcode.
//
// Returns OpSpec with tier set to TierSub1.
func sub1(op SubOpcode) OpSpec { return spec(TierSub1, uint8(op)) }

// sub2 starts a tier-2 row.
//
// Takes op (SubOpcodeTier2) which is the tier-2 sub-opcode.
//
// Returns OpSpec with tier set to TierSub2.
func sub2(op SubOpcodeTier2) OpSpec { return spec(TierSub2, uint8(op)) }

// sub3 starts a tier-3 row.
//
// Takes op (SubOpcodeTier3) which is the tier-3 sub-opcode.
//
// Returns OpSpec with tier set to TierSub3.
func sub3(op SubOpcodeTier3) OpSpec { return spec(TierSub3, uint8(op)) }

// symbolStem returns the CamelCase stem every symbol of an operation derives from, made
// of each underscore-separated word of the printed name with its first letter kept and
// the rest lowered, except initialisms.
//
// Takes name (string) which is the printed name.
//
// Returns string which is the stem, for example "LoadInt64Immediate".
func symbolStem(name string) string {
	var stem strings.Builder
	for word := range strings.SplitSeq(name, "_") {
		if symbolInitialisms[word] || word == "" {
			stem.WriteString(word)
			continue
		}
		stem.WriteString(word[:1])
		stem.WriteString(strings.ToLower(word[1:]))
	}
	return stem.String()
}

// deriveSymbols fills in a row's printed name from the generated name table and every
// symbol it has from the name's stem.
//
// Takes row (*OpSpec) which is the row to complete.
func deriveSymbols(row *OpSpec) {
	if names := specNames[row.Tier]; int(row.Code) < len(names) {
		row.Name = names[row.Code]
	}
	if row.Name == "" || row.Has(specReserved) {
		return
	}
	stem := symbolStem(row.Name)
	if row.symbols&symbolNoGoHandler == 0 {
		row.Handler = "handle" + stem
	}
	if row.symbols&symbolAsm != 0 {
		row.AsmBody = "handler" + stem
	}
	if row.symbols&symbolShim != 0 {
		row.Shim = stem
		row.ShimHandler = "Handle" + stem
	}
	if row.symbols&symbolExit != 0 {
		row.ExitStub = "handler" + stem + "Exit"
		row.ExitReason = "exit" + stem
	}
}

func init() {
	for _, rows := range [][]OpSpec{tierMainSpecs, tierSub1Specs, tierSub2Specs, tierSub3Specs} {
		for index := range rows {
			row := &rows[index]
			if specIndex[row.Tier][row.Code] != nil {
				panic(fmt.Sprintf("isa: duplicate spec row for tier %d code %d", row.Tier, row.Code))
			}
			deriveSymbols(row)
			specIndex[row.Tier][row.Code] = row
		}
	}
	buildJumpLayouts()
}
