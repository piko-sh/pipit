// Command gen_flat_switch parses the four dispatch registration maps in engine (emitted
// into vm_handler_table_generated.go by gen_opcode_tables.go) and emits a single 1024-arm
// switch dispatcher. The switch lets Go's Compiler lay out a jump table and inline the
// small handler bodies, which is faster than the equivalent function-pointer LUT.
//
// Run via:
//
//	go run gen_flat_switch.go
//
// or via the //go:generate directive in vm_handler_flat_table.go. The output path is
// fixed (vm_handler_flat_switch.go) so the progress lines can use stderr without
// polluting the generated file.
//
// The emitted file begins with the Go-standard
//
//	// Code generated ... DO NOT EDIT.
//
// header so linters and tools (golangci-lint, gopls) skip it.
//
// Both the parse and the Emit halves use go/ast. The Emit half constructs ast.SwitchStmt
// / ast.CaseClause / ast.ReturnStmt nodes directly and runs them through go/format, so
// identifier references in cases are real *ast.Ident values rather than text fragments;
// if a handler is renamed in the source maps, the generated switch reflects that rename
// without any string substitution.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
)

