// fastArgument builds the expression that reads one dispatcher argument, converted to the
// parameter's type.
//
// Takes argument (fastArg) which is the argument's shape.
// Takes index (int) which is its position in the call site's arguments.
// Takes closure (ast.Expr) which is the closure readNativeAnyArg receives, the cached
// callee or nil.
//
// Returns ast.Expr which is the argument.
// Returns error when the conversion does not parse.
func fastArgument(argument fastArg, index int, closure ast.Expr) (ast.Expr, error) {
	position := &ast.BasicLit{Kind: token.INT, Value: strconv.Itoa(index)}
	var read ast.Expr = &ast.CallExpr{
		Fun: ast.NewIdent(argument.Reader),
		Args: []ast.Expr{
			ast.NewIdent("registers"),
			&ast.IndexExpr{
				X:     &ast.SelectorExpr{X: ast.NewIdent("site"), Sel: ast.NewIdent("Arguments")},
				Index: position,
			},
		},
	}
	if argument.Any {
		read = &ast.CallExpr{
			Fun: ast.NewIdent("readNativeAnyArg"),
			Args: []ast.Expr{
				ast.NewIdent("vm"), closure, ast.NewIdent("site"), ast.NewIdent("registers"), position,
			},
		}
	}
	if argument.Conv == "" {
		return read, nil
	}
	conversion, err := gosource.Expression(argument.Conv)
	if err != nil {
		return nil, err
	}
	return &ast.CallExpr{Fun: conversion, Args: []ast.Expr{read}}, nil
}

// fastResult builds the statement that makes a dispatcher's call and stores its result.
//
// Takes row (fastDispatch) which is the dispatcher.
// Takes arguments ([]ast.Expr) which are the call's arguments.
//
// Returns ast.Stmt which is the call, or the store of its converted result.
// Returns error when the result conversion does not parse.
func fastResult(row fastDispatch, arguments []ast.Expr) (ast.Stmt, error) {
	var call ast.Expr = &ast.CallExpr{Fun: ast.NewIdent("f"), Args: arguments}
	if len(arguments) > 1 {
		call = gosource.ArgumentLines(&ast.CallExpr{Fun: ast.NewIdent("f"), Args: arguments})
	}
	if row.RetConv != "" {
		conversion, err := gosource.Expression(row.RetConv)
		if err != nil {
			return nil, err
		}
		call = &ast.CallExpr{Fun: conversion, Args: []ast.Expr{call}}
	}
	if row.RetBank == "" {
		return &ast.ExprStmt{X: call}, nil
	}
	return &ast.AssignStmt{
		Lhs: []ast.Expr{&ast.IndexExpr{
			X: &ast.SelectorExpr{X: ast.NewIdent("registers"), Sel: ast.NewIdent(row.RetBank)},
			Index: &ast.SelectorExpr{
				X: &ast.IndexExpr{
					X:     &ast.SelectorExpr{X: ast.NewIdent("site"), Sel: ast.NewIdent("Returns")},
					Index: &ast.BasicLit{Kind: token.INT, Value: "0"},
				},
				Sel: ast.NewIdent("Register"),
			},
		}},
		Tok: token.ASSIGN,
		Rhs: []ast.Expr{call},
	}, nil
}

// dispatcherParameters builds the site and registers parameters of a dispatcher, named
// "_" when its body reads neither.
//
// Takes row (fastDispatch) which is the dispatcher.
//
// Returns []*ast.Field which are the two parameters.
func dispatcherParameters(row fastDispatch) []*ast.Field {
	site, registers := "site", "registers"
	if len(row.Args) == 0 && row.RetBank == "" {
		site, registers = "_", "_"
	}
	return []*ast.Field{
		{
			Names: []*ast.Ident{ast.NewIdent(site)},
			Type:  &ast.StarExpr{X: &ast.SelectorExpr{X: ast.NewIdent("program"), Sel: ast.NewIdent("CallSite")}},
		},
		{Names: []*ast.Ident{ast.NewIdent(registers)}, Type: &ast.StarExpr{X: ast.NewIdent("Registers")}},
	}
}

// renderFastFamily builds every dispatcher.
//
// Returns []gosource.Declaration which holds the dispatchers in table order.
// Returns error when a table expression does not parse.
func renderFastFamily() ([]gosource.Declaration, error) {
	declarations := make([]gosource.Declaration, 0, len(fastDispatches))
	for _, row := range fastDispatches {
		signature, err := gosource.Expression(row.Sig)
		if err != nil {
			return nil, fmt.Errorf("fast-path dispatcher %s: %w", row.Name, err)
		}
		arguments := make([]ast.Expr, 0, len(row.Args))
		for index, argument := range row.Args {
			built, err := fastArgument(argument, index, ast.NewIdent("cached"))
			if err != nil {
				return nil, fmt.Errorf("fast-path dispatcher %s: %w", row.Name, err)
			}
			arguments = append(arguments, built)
		}
		result, err := fastResult(row, arguments)
		if err != nil {
			return nil, fmt.Errorf("fast-path dispatcher %s: %w", row.Name, err)
		}
		parameters := []*ast.Field{
			{Names: []*ast.Ident{ast.NewIdent("vm")}, Type: &ast.StarExpr{X: ast.NewIdent("VM")}},
			{Names: []*ast.Ident{ast.NewIdent("cached")}, Type: ast.NewIdent("any")},
		}
		declarations = append(declarations, gosource.Declaration{Node: &ast.FuncDecl{
			Name: ast.NewIdent("fpDispatch" + row.Name),
			Type: &ast.FuncType{Params: &ast.FieldList{List: append(parameters, dispatcherParameters(row)...)}},
			Body: &ast.BlockStmt{List: []ast.Stmt{
				&ast.AssignStmt{
					Lhs: []ast.Expr{ast.NewIdent("f"), ast.NewIdent("ok")},
					Tok: token.DEFINE,
					Rhs: []ast.Expr{&ast.TypeAssertExpr{X: ast.NewIdent("cached"), Type: signature}},
				},
				&ast.IfStmt{
					Cond: &ast.UnaryExpr{Op: token.NOT, X: ast.NewIdent("ok")},
					Body: &ast.BlockStmt{List: []ast.Stmt{
						&ast.AssignStmt{
							Lhs: []ast.Expr{ast.NewIdent("_")},
							Tok: token.ASSIGN,
							Rhs: []ast.Expr{&ast.CallExpr{
								Fun: ast.NewIdent("RecordFastPathTypeMismatch"),
								Args: []ast.Expr{
									ast.NewIdent("vm"),
									&ast.UnaryExpr{Op: token.SUB, X: &ast.BasicLit{Kind: token.INT, Value: "1"}},
									ast.NewIdent("fastPathDispatcherTag"),
									&ast.CallExpr{Fun: ast.NewIdent("reflectTypeName"), Args: []ast.Expr{ast.NewIdent("cached")}},
								},
							}},
						},
						&ast.ReturnStmt{},
					}},
				},
				result,
			}},
		}})
	}
	return declarations, nil
}

// renderFastMethodFamily builds every method-expression dispatcher, then their table.
//
// Returns []gosource.Declaration which holds the dispatchers and the table.
// Returns error when a table expression does not parse.
func renderFastMethodFamily() ([]gosource.Declaration, error) {
	declarations := make([]gosource.Declaration, 0, len(fastDispatches)+1)
	table := gosource.Lines(&ast.CompositeLit{
		Type: &ast.ArrayType{
			Len: &ast.BinaryExpr{
				X:  ast.NewIdent("fastPathTagBytesArr64"),
				Op: token.ADD,
				Y:  &ast.BasicLit{Kind: token.INT, Value: "1"},
			},
			Elt: ast.NewIdent("fastPathMethodDispatcher"),
		},
	})
	for _, row := range fastDispatches {
		parsed, err := gosource.Expression(row.Sig)
		if err != nil {
			return nil, fmt.Errorf("fast-path method dispatcher %s: %w", row.Name, err)
		}
		signature, ok := parsed.(*ast.FuncType)
		if !ok {
			return nil, fmt.Errorf("fast-path method dispatcher %s: %q is not a function type", row.Name, row.Sig)
		}
		signature.Params.List = append([]*ast.Field{{
			Type: &ast.SelectorExpr{X: ast.NewIdent("unsafe"), Sel: ast.NewIdent("Pointer")},
		}}, signature.Params.List...)
		vm := "_"
		arguments := []ast.Expr{ast.NewIdent("receiver")}
		for index, argument := range row.Args {
			if argument.Any {
				vm = "vm"
			}
			built, err := fastArgument(argument, index, ast.NewIdent("nil"))
			if err != nil {
				return nil, fmt.Errorf("fast-path method dispatcher %s: %w", row.Name, err)
			}
			arguments = append(arguments, built)
		}
		result, err := fastResult(row, arguments)
		if err != nil {
			return nil, fmt.Errorf("fast-path method dispatcher %s: %w", row.Name, err)
		}
		parameters := []*ast.Field{
			{Names: []*ast.Ident{ast.NewIdent(vm)}, Type: &ast.StarExpr{X: ast.NewIdent("VM")}},
			{
				Names: []*ast.Ident{ast.NewIdent("expression"), ast.NewIdent("receiver")},
				Type:  &ast.SelectorExpr{X: ast.NewIdent("unsafe"), Sel: ast.NewIdent("Pointer")},
			},
		}
		declarations = append(declarations, gosource.Declaration{Node: &ast.FuncDecl{
			Name: ast.NewIdent("fpMethodDispatch" + row.Name),
			Type: &ast.FuncType{Params: &ast.FieldList{List: append(parameters, dispatcherParameters(row)...)}},
			Body: &ast.BlockStmt{List: []ast.Stmt{
				&ast.AssignStmt{
					Lhs: []ast.Expr{ast.NewIdent("f")},
					Tok: token.DEFINE,
					Rhs: []ast.Expr{&ast.StarExpr{X: &ast.CallExpr{
						Fun: &ast.ParenExpr{X: &ast.StarExpr{X: signature}},
						Args: []ast.Expr{&ast.CallExpr{
							Fun:  &ast.SelectorExpr{X: ast.NewIdent("unsafe"), Sel: ast.NewIdent("Pointer")},
							Args: []ast.Expr{&ast.UnaryExpr{Op: token.AND, X: ast.NewIdent("expression")}},
						}},
					}}},
				},
				result,
			}},
		}})
		table.Elts = append(table.Elts, &ast.KeyValueExpr{
			Key:   ast.NewIdent("fastPathTag" + row.Name),
			Value: ast.NewIdent("fpMethodDispatch" + row.Name),
		})
	}
	return append(declarations, gosource.Declaration{
		Doc: []string{
			"fastPathMethodDispatchTable holds each generated tag's method-expression dispatcher.",
		},
		Node: &ast.GenDecl{
			Tok: token.VAR,
			Specs: []ast.Spec{&ast.ValueSpec{
				Names:  []*ast.Ident{ast.NewIdent("fastPathMethodDispatchTable")},
				Values: []ast.Expr{table},
			}},
		},
	}), nil
}

