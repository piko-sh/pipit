// fastDispatch describes one dispatcher: the asserted function type, how each argument is
// read, and where the result goes.
type fastDispatch struct {
	// Name is the dispatcher suffix after fpDispatch ("StringInt").
	Name string

	// Sig is the asserted Go function type ("func(string) int").
	Sig string

	// Args are the arguments in call order.
	Args []fastArg

	// RetBank is the Registers field receiving the result; empty for void functions.
	RetBank string

	// RetConv is the conversion applied to the result when the bank type differs from the
	// return type, or empty for none.
	RetConv string
}

