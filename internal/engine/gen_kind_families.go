// sliceKind describes one typed-slice element kind: the banks it lives in and which
// members of the family it has, with the per-kind expressions the templates splice in.
type sliceKind struct {
	// Kind is the capitalised kind token in handler names ("Float").
	Kind string

	// Elem is the Go element type ("float64").
	Elem string

	// SliceBank is the Registers field holding slices of Elem ("slicesFloat").
	SliceBank string

	// ScalarBank is the Registers field holding single Elem values ("Floats").
	ScalarBank string

	// Alloc is the RegisterArena method that allocates a backing array
	// ("AllocFloatBacking").
	Alloc string

	// Make emits handleSubOpMakeSlice<Kind>.
	Make bool

	// GetName names the tier-1 element get handler. Empty skips it.
	GetName string

	// SetName names the tier-1 element set handler. Empty skips it.
	SetName string

	// ReadExpr converts slice[index] into the scalar bank's type for get and range-next.
	ReadExpr string

	// StoreExpr is the value the set handler stores into slice[index].
	StoreExpr string

	// LenCap emits handleSubOpLenSlice<Kind>Direct and handleSubOpCapSlice<Kind>Direct.
	LenCap bool

	// SliceSliceName names the three-index slicing handler; empty skips it.
	SliceSliceName string

	// AppendElem is the element expression of handleSubOpAppendSlice<Kind>Direct; empty
	// skips it.
	AppendElem string

	// RangeNext emits handleRangeNextSlice<Kind>.
	RangeNext bool
}

