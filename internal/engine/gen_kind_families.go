// main parses flags and runs the generator.
func main() {
	validate := flag.Bool("validate", false,
		"compare the committed files against the generated ones instead of writing them")
	flag.Parse()

	if err := run(*validate); err != nil {
		fmt.Fprintf(os.Stderr, "gen_kind_families: %v\n", err)
		os.Exit(1)
	}
}

// run renders both files in memory and then either validates or writes them.
//
// Takes validate (bool) which selects comparison against the committed files over
// writing.
//
// Returns error which is the first failure, or the validation verdict.
func run(validate bool) error {
	files, err := emitAll()
	if err != nil {
		return err
	}
	if validate {
		return validateFiles(files)
	}
	return writeFiles(files)
}

// emitAll renders the typed-slice and fast-path files.
//
// Returns []outputFile which are the formatted files.
// Returns error when a template fails or the output does not parse.
func emitAll() ([]outputFile, error) {
	sliceBody, err := renderSliceFamily()
	if err != nil {
		return nil, err
	}
	fastBody, err := renderFastFamily()
	if err != nil {
		return nil, err
	}
	flatBody, err := renderFlatFamily()
	if err != nil {
		return nil, err
	}
	appendBody, err := renderAppendAdapterFamily()
	if err != nil {
		return nil, err
	}
	specs := []struct {
		path    string
		imports [][]string
		body    string
	}{
		{path: sliceOutputPath, imports: [][]string{{"fmt", "unsafe"}, {"pipit.sh/pipit/internal/fault", "pipit.sh/pipit/internal/isa", "pipit.sh/pipit/internal/safeconv"}}, body: sliceBody},
		{path: fastPathOutputPath, imports: [][]string{{"pipit.sh/pipit/internal/engine/program", "pipit.sh/pipit/internal/safeconv"}}, body: fastBody},
		{path: flatWrapperOutputPath, imports: [][]string{{"pipit.sh/pipit/internal/isa"}}, body: flatBody},
		{path: appendAdapterOutputPath, imports: [][]string{{"pipit.sh/pipit/internal/isa"}}, body: appendBody},
	}
	files := make([]outputFile, 0, len(specs))
	for _, spec := range specs {
		formatted, err := format.Source([]byte(fileText(spec.imports, spec.body)))
		if err != nil {
			return nil, fmt.Errorf("%s: generated source does not parse: %w", spec.path, err)
		}
		files = append(files, outputFile{path: spec.path, content: formatted})
	}
	return files, nil
}

