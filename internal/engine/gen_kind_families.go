// handlerType builds the signature every bytecode handler shares.
//
// Takes vmName (string) which names the *VM parameter, "_" when unused.
// Takes frameName (string) which names the *CallFrame parameter, "_" when unused.
// Takes instructionName (string) which names the isa.Instruction parameter.
//
// Returns *ast.FuncType which is the signature.
func handlerType(vmName, frameName, instructionName string) *ast.FuncType {
	return &ast.FuncType{
		Params: &ast.FieldList{List: []*ast.Field{
			{Names: []*ast.Ident{ast.NewIdent(vmName)}, Type: &ast.StarExpr{X: ast.NewIdent("VM")}},
			{Names: []*ast.Ident{ast.NewIdent(frameName)}, Type: &ast.StarExpr{X: ast.NewIdent("CallFrame")}},
			{Names: []*ast.Ident{ast.NewIdent("registers")}, Type: &ast.StarExpr{X: ast.NewIdent("Registers")}},
			{
				Names: []*ast.Ident{ast.NewIdent(instructionName)},
				Type:  &ast.SelectorExpr{X: ast.NewIdent("isa"), Sel: ast.NewIdent("Instruction")},
			},
		}},
		Results: &ast.FieldList{List: []*ast.Field{{Type: ast.NewIdent("OpResult")}}},
	}
}

// renderSliceFamily builds every member of every typed-slice kind.
//
// Returns []gosource.Declaration which holds the handlers in kind order.
// Returns error when a table expression does not parse.
func renderSliceFamily() ([]gosource.Declaration, error) {
	var declarations []gosource.Declaration
	for _, kind := range sliceKinds {
		built, err := sliceKindHandlers(kind)
		if err != nil {
			return nil, fmt.Errorf("slice kind %s: %w", kind.Kind, err)
		}
		for _, function := range built {
			declarations = append(declarations, gosource.Declaration{Node: function})
		}
	}
	return declarations, nil
}

