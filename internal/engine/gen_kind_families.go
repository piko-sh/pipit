// fastArg is one argument of a native fast-path dispatcher.
type fastArg struct {
	// Read is the register-reading expression with %d for the argument index.
	Read string

	// Conv wraps Read with %s when the Go parameter type differs from the bank type.
	Conv string
}

var (
	// stringArg is the fast-path shape for a string parameter.
	stringArg = fastArg{Read: readString, Conv: ""}

	// intArg is the fast-path shape for an int parameter.
	intArg = fastArg{Read: readInt, Conv: "int(%s)"}

	// int64Arg is the fast-path shape for an int64 parameter.
	int64Arg = fastArg{Read: readInt, Conv: ""}

	// runeArg is the fast-path shape for a rune parameter.
	runeArg = fastArg{Read: readInt, Conv: "safeconv.Int64ToInt32(%s)"}

	// floatArg is the fast-path shape for a float64 parameter.
	floatArg = fastArg{Read: readFloat, Conv: ""}

	// boolArg is the fast-path shape for a bool parameter.
	boolArg = fastArg{Read: readBool, Conv: ""}

	// anyArg is the fast-path shape for an any parameter.
	anyArg = fastArg{Read: readAny, Conv: ""}
)

// fastDispatch describes one dispatcher: the asserted function type, how each argument is
// read, and where the result goes.
type fastDispatch struct {
	// Name is the dispatcher suffix after fpDispatch ("StringInt").
	Name string

	// Sig is the asserted Go function type ("func(string) int").
	Sig string

	// Args are the arguments in call order.
	Args []fastArg

	// RetBank is the Registers field receiving the result; empty for void functions.
	RetBank string

	// RetConv wraps the call with %s when the bank type differs from the return type.
	RetConv string
}

// fastView is the template input for one dispatcher: the row plus the rendered call and
// the parameter names, which become blanks when the body never reads them.
type fastView struct {
	fastDispatch

	// Call is the rendered f(args) expression.
	Call string

	// SiteParam is the site parameter name, or "_" when unused.
	SiteParam string

	// RegistersParam is the registers parameter name, or "_".
	RegistersParam string
}

// flatWrapper describes one Pattern C wrapper: the sub-op name suffix, the tier-0 handler
// it dispatches to, and whether the sub-op carries one operand (in C) or two (in B and
// C).
type flatWrapper struct {
	// Name is the suffix after handleFlatSubOp ("MoveInt").
	Name string

	// Inner is the handler that receives the reshaped instruction ("handleMoveInt").
	Inner string

	// Unary maps instr.C to A; otherwise instr.B and instr.C map to A and B.
	Unary bool
}

