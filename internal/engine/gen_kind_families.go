// fastArg is one argument of a native fast-path dispatcher.
type fastArg struct {
	// Reader is the function that reads the argument's register, unused when Any is set.
	Reader string

	// Conv is the conversion applied to the read value when the Go parameter type differs
	// from the bank type, or empty for none.
	Conv string

	// Any reads the argument through readNativeAnyArg.
	Any bool
}

