// outputFile is one rendered file and where it lives.
type outputFile struct {
	// path is the output file path.
	path string

	// content is the gofmt-formatted file bytes.
	content []byte
}

// renderCall renders f(args) for one row, one argument per line when there are several,
// wrapped by RetConv when set.
//
// Takes row (fastDispatch) which is the dispatcher.
//
// Returns string which is the call expression.
func renderCall(row fastDispatch) string {
	args := make([]string, 0, len(row.Args))
	for index, argument := range row.Args {
		expr := fmt.Sprintf(argument.Read, index)
		if argument.Conv != "" {
			expr = fmt.Sprintf(argument.Conv, expr)
		}
		args = append(args, expr)
	}
	var call string
	switch len(args) {
	case 0:
		call = "f()"
	case 1:
		call = "f(" + args[0] + ")"
	default:
		call = "f(\n\t\t" + strings.Join(args, ",\n\t\t") + ",\n\t)"
	}
	if row.RetConv != "" {
		call = fmt.Sprintf(row.RetConv, call)
	}
	return call
}

