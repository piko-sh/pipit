// Command gen_spec_names emits the printed name of every operation, derived from its enum
// constant in internal/isa/opcode.go.
//
// Run go run gen_spec_names.go from internal/engine. With -validate, the program
// regenerates in memory, compares against the committed file and exits 1 when it differs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"strconv"
	"strings"
	"unicode"

	"pipit.sh/pipit/internal/gosource"
)

const (
	// opcodeSourcePath is the isa enum source, relative to internal/engine.
	opcodeSourcePath = "../isa/opcode.go"

	// outputPath is the generated name table, relative to internal/engine.
	outputPath = "../isa/spec_names_generated.go"

	// tierCount is the number of encoding tiers.
	tierCount = 4

	// slotCount is the number of codes per tier.
	slotCount = 256

	// outputFileMode is the permission of the written file.
	outputFileMode = 0o644
)

