// errUnknownDeclaration reports a forward declaration that names no handler definition.
var errUnknownDeclaration = errors.New("asm: goDeclarations names a symbol no handler definition defines")

// dispatchGoFiles returns the generated Go files that pair with the dispatch assembly.
//
// asmgen.GoFile carries one Name and one Emit, with no per-architecture fan-out, so the
// architecture split is expressed as three entries whose Emit closures filter for their
// own architecture rather than by extending the upstream type.
//
// Returns []asmgen.GoFile which is the generated file list.
func dispatchGoFiles() []asmgen.GoFile {
	architectures := []asmgen.Architecture{asmgen.ArchitectureAMD64, asmgen.ArchitectureARM64}
	files := make([]asmgen.GoFile, 0, 1+len(architectures))
	files = append(files, asmgen.GoFile{
		Name: "vm_dispatch_shared_generated.go",
		Dir:  dispatchGoOutputDir,
		Emit: func(_ []asmgen.ArchitecturePort) string {
			return emitSharedDispatchFile()
		},
	})

	for _, architecture := range architectures {
		files = append(files, asmgen.GoFile{
			Name: fmt.Sprintf("vm_dispatch_%s_generated.go", architecture),
			Dir:  dispatchGoOutputDir,
			Emit: func(_ []asmgen.ArchitecturePort) string {
				return emitArchitectureDispatchFile(architecture)
			},
		})
	}

	return files
}

// handlerSynopsisIndex maps every handler name to its assembly comment.
//
// The comment is the single source of the symbol's one-line description: emitting the Go
// doc comment from it is what keeps the prototype and the TEXT block from describing the
// same handler differently.
//
// Returns map[string]string which maps handler name to its synopsis.
func handlerSynopsisIndex() map[string]string {
	synopses := make(map[string]string)
	for _, group := range FileGroups() {
		for _, handler := range group.Handlers {
			synopses[handler.Name] = handler.Comment
		}
	}
	return synopses
}

// declarationsFor selects the declarations belonging to one output file.
//
// Takes architecture (asmgen.Architecture) which filters the declarations, or empty for
// the shared file.
//
// Returns []goDeclaration which is the matching declarations.
func declarationsFor(architecture asmgen.Architecture) []goDeclaration {
	var selected []goDeclaration
	for _, declaration := range goDeclarations() {
		if architecture == "" {
			if declaration.Architectures == nil {
				selected = append(selected, declaration)
			}
			continue
		}
		if declarationTargets(declaration.Architectures, architecture) && declaration.Architectures != nil {
			selected = append(selected, declaration)
		}
	}
	return selected
}

// declarationTargets reports whether a restriction list covers an architecture.
//
// Takes architectures ([]asmgen.Architecture) which is the restriction list, or nil for
// unrestricted.
// Takes architecture (asmgen.Architecture) which is the architecture to test.
//
// Returns bool which is true when the architecture is covered.
func declarationTargets(architectures []asmgen.Architecture, architecture asmgen.Architecture) bool {
	if architectures == nil {
		return true
	}
	return slices.Contains(architectures, architecture)
}

// emitSharedDispatchFile returns the source of the architecture-independent dispatch
// file.
//
// Returns string which is the generated Go source.
func emitSharedDispatchFile() string {
	prototypes, err := prototypeDeclarations("")
	if err != nil {
		return failedGoFile(err)
	}
	install := &ast.BlockStmt{}
	for _, step := range initSequence() {
		if step.Shared {
			install.List = append(install.List, &ast.ExprStmt{X: step.Call})
		}
	}
	declarations := make([]gosource.Declaration, 0, len(prototypes)+2)
	declarations = append(declarations, gosource.Declaration{Doc: nil, Directives: nil, Node: &ast.GenDecl{
		Tok:    token.VAR,
		Lparen: 1,
		Specs: []ast.Spec{&ast.ValueSpec{
			Names: []*ast.Ident{ast.NewIdent("asmJumpTable")},
			Type:  &ast.ArrayType{Len: ast.NewIdent("opcodeTableSize"), Elt: ast.NewIdent("uintptr")},
		}},
	}})
	declarations = append(declarations, prototypes...)
	declarations = append(declarations, gosource.Declaration{Doc: nil, Directives: nil, Node: &ast.FuncDecl{
		Name: ast.NewIdent("installDispatchTables"),
		Type: &ast.FuncType{Params: &ast.FieldList{}},
		Body: install,
	}})
	return renderGoFile(&gosource.File{
		Header:                    generatedGoNotice + "\n\n" + licenceHeaderText,
		BuildConstraint:           sharedDispatchBuildConstraint,
		Package:                   "engine",
		ImportGroups:              nil,
		LoneImportUnparenthesised: false,
		Declarations:              declarations,
	})
}

// emitArchitectureDispatchFile returns the source of one architecture's dispatch file.
//
// Takes architecture (asmgen.Architecture) which selects the target architecture.
//
// Returns string which is the generated Go source.
func emitArchitectureDispatchFile(architecture asmgen.Architecture) string {
	prototypes, err := prototypeDeclarations(architecture)
	if err != nil {
		return failedGoFile(err)
	}
	steps := initStepsFor(architecture)

	var importPaths []string
	initialise := &ast.BlockStmt{}
	for _, step := range steps {
		if step.Shared {
			continue
		}
		if step.GuardImport != "" {
			importPaths = append(importPaths, step.GuardImport)
		}
		var statement ast.Stmt = &ast.ExprStmt{X: step.Call}
		if step.Guard != nil {
			statement = &ast.IfStmt{Cond: step.Guard, Body: &ast.BlockStmt{List: []ast.Stmt{statement}}}
		}
		initialise.List = append(initialise.List, statement)
	}
	initialise.List = append(initialise.List, &ast.ExprStmt{X: &ast.CallExpr{Fun: ast.NewIdent("installDispatchTables")}})
	slices.Sort(importPaths)
	importPaths = dedupeStrings(importPaths)
	imports := make([]gosource.Import, 0, len(importPaths))
	for _, path := range importPaths {
		imports = append(imports, gosource.Import{Path: path, Name: ""})
	}

	prototypes = append(prototypes, gosource.Declaration{Doc: nil, Directives: nil, Node: &ast.FuncDecl{
		Name: ast.NewIdent("init"),
		Type: &ast.FuncType{Params: &ast.FieldList{}},
		Body: initialise,
	}})
	return renderGoFile(&gosource.File{
		Header:          generatedGoNotice + "\n\n" + licenceHeaderText,
		BuildConstraint: "!safe && !(js && wasm) && " + string(architecture),
		Package:         "engine",
		ImportGroups:    [][]gosource.Import{imports},
		Declarations:    prototypes,

		LoneImportUnparenthesised: false,
	})
}

// initStepsFor selects the init sequence entries that run on one architecture.
//
// Takes architecture (asmgen.Architecture) which selects the target architecture.
//
// Returns []initStep which is the filtered init steps.
func initStepsFor(architecture asmgen.Architecture) []initStep {
	var selected []initStep
	for _, step := range initSequence() {
		if declarationTargets(step.Architectures, architecture) {
			selected = append(selected, step)
		}
	}
	return selected
}

// dedupeStrings removes adjacent duplicates from a sorted slice.
//
// Takes values ([]string) which is the sorted input.
//
// Returns []string which is the deduplicated result.
func dedupeStrings(values []string) []string {
	var unique []string
	for i, value := range values {
		if i > 0 && value == values[i-1] {
			continue
		}
		unique = append(unique, value)
	}
	return unique
}

// prototypeDeclarations builds the forward declarations belonging to one output file.
//
// Takes architecture (asmgen.Architecture) which filters the declarations, or empty for
// the shared file.
//
// Returns []gosource.Declaration which holds one bodiless function per declaration.
// Returns error when a declaration names no handler definition.
func prototypeDeclarations(architecture asmgen.Architecture) ([]gosource.Declaration, error) {
	synopses := handlerSynopsisIndex()
	selected := declarationsFor(architecture)
	prototypes := make([]gosource.Declaration, 0, len(selected))
	for _, declaration := range selected {
		if _, ok := synopses[declaration.Name]; !ok {
			return nil, fmt.Errorf("%w: %q", errUnknownDeclaration, declaration.Name)
		}
		prototypes = append(prototypes, gosource.Declaration{
			Doc:        nil,
			Directives: []string{"go:noescape"},
			Node: &ast.FuncDecl{
				Name: ast.NewIdent(declaration.Name),
				Type: &ast.FuncType{Params: &ast.FieldList{List: declaration.Parameters}},
			},
		})
	}
	return prototypes, nil
}

// renderGoFile prints a generated Go file.
//
// Takes file (*gosource.File) which is the file to print.
//
// Returns string which is the source, or a file that fails to compile and names the error
// when printing fails.
func renderGoFile(file *gosource.File) string {
	source, err := file.Render()
	if err != nil {
		return failedGoFile(err)
	}
	return string(source)
}

// failedGoFile stands in for a file the generator could not build.
//
// Takes err (error) which is why the file could not be built.
//
// Returns string which is the stand-in text.
func failedGoFile(err error) string {
	return "asmgen could not generate this file: " + err.Error() + "\n"
}
