func TestRenderPrintsAFileInGofmtForm(t *testing.T) {
	t.Parallel()
	file := File{
		Header:          "// Code generated by a test. DO NOT EDIT.",
		BuildConstraint: "amd64 || arm64",
		Package:         "sample",
		ImportGroups: [][]Import{
			{{Path: "fmt", Name: ""}, {Path: "strings", Name: ""}},
			{{Path: "pipit.sh/pipit/internal/isa", Name: "opcodes"}},
		},
		Declarations: []Declaration{
			{
				Doc: []string{"answer is the answer.", "", "It is a constant."},
				Node: &ast.GenDecl{
					Tok: token.CONST,
					Specs: []ast.Spec{&ast.ValueSpec{
						Names:  []*ast.Ident{ast.NewIdent("answer")},
						Values: []ast.Expr{&ast.BasicLit{Kind: token.INT, Value: "42"}},
					}},
				},
			},
		},
	}

	source, err := file.Render()

	require.NoError(t, err)
	require.Equal(t, `// Code generated by a test. DO NOT EDIT.

//go:build amd64 || arm64

package sample

import (
	"fmt"
	"strings"

	opcodes "pipit.sh/pipit/internal/isa"
)

// answer is the answer.
//
// It is a constant.
const answer = 42
`, string(source))
}

