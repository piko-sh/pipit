func TestArgumentLinesPutsEachArgumentOnItsOwnLine(t *testing.T) {
	t.Parallel()
	call := ArgumentLines(&ast.CallExpr{
		Fun:  ast.NewIdent("f"),
		Args: []ast.Expr{ast.NewIdent("first"), &ast.CallExpr{Fun: ast.NewIdent("second")}},
	})
	file := File{
		Package: "sample",
		Declarations: []Declaration{{Node: &ast.FuncDecl{
			Name: ast.NewIdent("caller"),
			Type: &ast.FuncType{Params: &ast.FieldList{}},
			Body: &ast.BlockStmt{List: []ast.Stmt{
				&ast.AssignStmt{Lhs: []ast.Expr{ast.NewIdent("_")}, Tok: token.ASSIGN, Rhs: []ast.Expr{call}},
			}},
		}}},
	}

	source, err := file.Render()

	require.NoError(t, err)
	require.Equal(t, "package sample\n\nfunc caller() {\n\t_ = f(\n\t\tfirst,\n\t\tsecond(),\n\t)\n}\n", string(source))
}

func TestRenderPrintsADocumentedStructWithItsFieldComments(t *testing.T) {
	t.Parallel()
	field := func(name, kind, doc string) *ast.Field {
		return &ast.Field{
			Doc:   &ast.CommentGroup{List: []*ast.Comment{{Text: "// " + doc}}},
			Names: []*ast.Ident{ast.NewIdent(name)},
			Type:  ast.NewIdent(kind),
		}
	}
	file := File{
		Package: "sample",
		Declarations: []Declaration{{
			Doc: []string{"entry is one entry."},
			Node: &ast.GenDecl{
				Tok: token.TYPE,
				Specs: []ast.Spec{&ast.TypeSpec{
					Name: ast.NewIdent("entry"),
					Type: &ast.StructType{Fields: &ast.FieldList{List: []*ast.Field{
						field("Path", "string", "Path is where it lives."),
						field("Size", "int", "Size is how big it is."),
					}}},
				}},
			},
		}},
	}

	source, err := file.Render()

	require.NoError(t, err)
	require.Equal(t, `package sample

// entry is one entry.
type entry struct {
	// Path is where it lives.
	Path string

	// Size is how big it is.
	Size int
}
`, string(source))
}
